/// Screen 5 — Patient clinical record.
///
/// Renders the Critical Health Summary the backend returns, plus its
/// rule-based alerts. Every field shown exists in the record; anything NEMRAS
/// does not hold is rendered as "Not available" rather than filled in.
class PatientClinicalRecordScreen extends StatelessWidget {
  const PatientClinicalRecordScreen({super.key, required this.onNavigate});

  final ValueChanged<int> onNavigate;

  @override
  Widget build(BuildContext context) {
    final controller = HospitalSessionScope.of(context);
    final semantics = NemrasSemantics.of(context);

    switch (controller.recordState) {
      case LoadState.loading:
        return const ClinicalLoadingState(message: 'Opening record…');
      case LoadState.failed:
        return ClinicalErrorState(
          message:
              controller.recordError ?? 'The record could not be opened.',
          onRetry: () =>
              onNavigate(HospitalClinicalNavigation.patientsIndex),
        );
      case LoadState.idle:
      case LoadState.ready:
        break;
    }

    final record = controller.record;
    if (record == null) {
      return ClinicalEmptyState(
        icon: Icons.folder_shared_outlined,
        title: 'No record open',
        message:
            'Search for a patient by CNIC to open their clinical record.',
        action: FilledButton.icon(
          onPressed: () =>
              onNavigate(HospitalClinicalNavigation.patientsIndex),
          icon: const Icon(Icons.search, size: 16),
          label: const Text('Patient search'),
        ),
      );
    }

    final summary = record.summary;

    return ClinicalContentArea(
      children: <Widget>[
        if (controller.isBreakGlassAccess)
          _BreakGlassBanner(reason: controller.breakGlassReason),
        _RecordHeader(summary: summary),
        ClinicalCard(
          title: 'Rule-based record alerts',
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: <Widget>[
              Text(
                'Generated by explicit rules over the recorded fields. These '
                'are not the output of a trained model and carry no clinical '
                'validation.',
                style: NemrasTextStyles.bodyCaption.copyWith(
                  color: semantics.textSecondary,
                ),
              ),
              const SizedBox(height: NemrasSpacing.xl),
              if (record.alerts.isEmpty)
                Text(
                  'The backend returned no alerts for this record.',
                  style: NemrasTextStyles.bodySmall.copyWith(
                    color: semantics.textSecondary,
                  ),
                )
              else
                for (var i = 0; i < record.alerts.length; i++) ...<Widget>[
                  if (i > 0) const SizedBox(height: NemrasSpacing.l),
                  ClinicalAlertBox(
                    title: record.alerts[i].title,
                    detail: record.alerts[i].detail,
                    status: semantics.severity(record.alerts[i].severity),
                  ),
                ],
            ],
          ),
        ),
        ClinicalSplitPanels(
          primary: ClinicalCard(
            title: 'Clinical fields',
            child: ClinicalWrapGrid(
              minCellWidth: 170,
              children: <Widget>[
                ClinicalDataField(
                  label: 'Medical condition',
                  value: summary.medicalCondition,
                ),
                ClinicalDataField(
                  label: 'Chronic condition',
                  value: summary.chronicCondition,
                ),
                ClinicalDataField(
                  label: 'Medication',
                  value: summary.medication,
                ),
                ClinicalDataField(label: 'Allergy', value: summary.allergy),
                ClinicalDataField(
                  label: 'Drug interaction risk',
                  value: summary.drugInteractionRisk,
                ),
                ClinicalDataField(
                  label: 'Test results',
                  value: summary.testResults,
                ),
              ],
            ),
          ),
          secondary: ClinicalCard(
            title: 'Admission',
            child: ClinicalWrapGrid(
              minCellWidth: 150,
              children: <Widget>[
                ClinicalDataField(
                  label: 'Admission type',
                  value: summary.admissionType,
                ),
                ClinicalDataField(
                  label: 'Admitted',
                  value: summary.admissionDate,
                ),
                ClinicalDataField(
                  label: 'Discharged',
                  value: summary.dischargeDate,
                ),
                ClinicalDataField(
                  label: 'Hospital',
                  value: summary.hospital,
                ),
                ClinicalDataField(
                  label: 'Attending doctor',
                  value: summary.doctor,
                ),
                ClinicalDataField(
                  label: 'Insurance provider',
                  value: summary.insuranceProvider,
                ),
              ],
            ),
          ),
        ),
        const ClinicalCard(
          title: 'Not held by NEMRAS',
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: <Widget>[
              ProvenanceNotice(
                icon: Icons.remove_circle_outline,
                message:
                    'NEMRAS records no vital signs, numeric laboratory '
                    'panels, imaging, ICD coding or bed assignment. These '
                    'fields are shown as unavailable rather than estimated.',
              ),
              SizedBox(height: NemrasSpacing.xl),
              ClinicalWrapGrid(
                minCellWidth: 170,
                children: <Widget>[
                  ClinicalDataField(label: 'Vital signs', value: kNotAvailable),
                  ClinicalDataField(
                    label: 'Laboratory panel',
                    value: kNotAvailable,
                  ),
                  ClinicalDataField(label: 'ICD code', value: kNotAvailable),
                  ClinicalDataField(label: 'Imaging', value: kNotAvailable),
                ],
              ),
            ],
          ),
        ),
        Row(
          children: <Widget>[
            OutlinedButton.icon(
              onPressed: () =>
                  onNavigate(HospitalClinicalNavigation.medicationsIndex),
              icon: const Icon(Icons.medication_outlined, size: 16),
              label: const Text('Medication safety'),
            ),
            const SizedBox(width: NemrasSpacing.l),
            OutlinedButton.icon(
              onPressed: () =>
                  onNavigate(HospitalClinicalNavigation.assistantIndex),
              icon: const Icon(Icons.forum_outlined, size: 16),
              label: const Text('Clinical assistant'),
            ),
            const SizedBox(width: NemrasSpacing.l),
            TextButton.icon(
              onPressed: controller.clearRecord,
              icon: const Icon(Icons.close, size: 16),
              label: const Text('Close record'),
            ),
          ],
        ),
      ],
    );
  }
}

class _BreakGlassBanner extends StatelessWidget {
  const _BreakGlassBanner({required this.reason});

  final String? reason;

  @override
  Widget build(BuildContext context) {
    final semantics = NemrasSemantics.of(context);
    return Container(
      width: double.infinity,
      padding: const EdgeInsets.all(NemrasSpacing.xl),
      decoration: BoxDecoration(
        color: semantics.critical.soft,
        borderRadius: NemrasRadii.controlBorder,
        border: Border.all(color: semantics.critical.solid),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: <Widget>[
          Row(
            children: <Widget>[
              Icon(
                Icons.lock_open,
                size: 16,
                color: semantics.critical.onSoft,
              ),
              const SizedBox(width: NemrasSpacing.s),
              Expanded(
                child: Text(
                  'Opened with break-glass emergency access',
                  style: NemrasTextStyles.alertTitle.copyWith(
                    color: semantics.critical.onSoft,
                  ),
                ),
              ),
              const DemoChip(label: 'DEMO AUDIT'),
            ],
          ),
          if (reason != null && reason!.isNotEmpty) ...<Widget>[
            const SizedBox(height: NemrasSpacing.m),
            ClinicalDataField(
              label: 'Recorded reason',
              value: reason!,
              emphasise: true,
            ),
          ],
        ],
      ),
    );
  }
}

class _RecordHeader extends StatelessWidget {
  const _RecordHeader({required this.summary});

  final PatientClinicalSummary summary;

  @override
  Widget build(BuildContext context) {
    final semantics = NemrasSemantics.of(context);
    final critical = summary.riskScore == 'Critical';

    return Container(
      width: double.infinity,
      padding: const EdgeInsets.all(NemrasSpacing.section),
      decoration: BoxDecoration(
        gradient: LinearGradient(
          begin: Alignment.topLeft,
          end: Alignment.bottomRight,
          colors: critical
              ? semantics.criticalSummaryGradient
              : semantics.summaryGradient,
        ),
        borderRadius: NemrasRadii.cardBorder,
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: <Widget>[
          Text(
            summary.patientName,
            style: NemrasTextStyles.summaryName.copyWith(
              color: NemrasColors.white,
            ),
          ),
          const SizedBox(height: NemrasSpacing.xxs),
          Text(
            '${summary.cnic}  ·  ${summary.gender}  ·  '
            'AGE ${summary.ageLabel}  ·  ${summary.bloodType}',
            style: NemrasTextStyles.dataCaption.copyWith(
              color: NemrasColors.fieldTextSecondary,
            ),
          ),
          const SizedBox(height: NemrasSpacing.xl),
          Wrap(
            spacing: NemrasSpacing.s,
            runSpacing: NemrasSpacing.s,
            children: <Widget>[
              ClinicalStatusPill(
                label: 'RISK ${summary.riskScore}',
                status: semantics.risk(summary.riskScore),
              ),
              ClinicalStatusPill(
                label: 'TRIAGE ${summary.triageLevel}',
                status: semantics.triage(summary.triageLevel),
              ),
              if (summary.hasRecordedAllergy)
                ClinicalStatusPill(
                  label: 'ALLERGY',
                  status: semantics.allergy,
                  icon: Icons.warning_amber_outlined,
                ),
              if (summary.hasDrugInteractionFlag)
                ClinicalStatusPill(
                  label: 'INTERACTION FLAG',
                  status: semantics.drugInteraction(present: true),
                ),
            ],
          ),
          const SizedBox(height: NemrasSpacing.l),
          Text(
            'Risk_Score is a categorical dataset label, not a clinically '
            'validated probability.',
            style: NemrasTextStyles.bodyCaption.copyWith(
              color: NemrasColors.fieldTextTertiary,
            ),
          ),
        ],
      ),
    );
  }
}
