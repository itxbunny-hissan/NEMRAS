/// Screen 3 — Bed and Room Occupancy.
///
/// Everything on this screen is DEMO. `Room_Number` is a column in
/// `NEMRAS_Dataset.csv`, but it is a bare per-record string with no state, no
/// timestamp and no ward, no backend route exposes it, and the patient
/// summary the API returns omits it entirely. A room is therefore not
/// something NEMRAS can observe, so the room identifiers here are formatted
/// after that column and nothing more.
class BedOccupancyScreen extends StatelessWidget {
  const BedOccupancyScreen({super.key});

  @override
  Widget build(BuildContext context) {
    final controller = OpsScope.of(context);
    final semantics = NemrasSemantics.of(context);

    if (controller.occupancyState.isLoading) {
      return const OpsLoadingState(message: 'Reading demo occupancy state');
    }
    if (controller.occupancyState.hasFailed) {
      return OpsErrorState(
        title: 'Occupancy state unavailable',
        message: controller.occupancyError ??
            'The demo occupancy provider returned an error.',
        onRetry: controller.refreshOccupancy,
      );
    }

    final snapshot = controller.occupancy;
    if (snapshot == null || snapshot.wards.isEmpty) {
      return const OpsEmptyState(
        title: 'No occupancy data',
        message: 'The demo occupancy provider reported no wards.',
        icon: Icons.bed_outlined,
      );
    }

    return OpsContentArea(
      children: <Widget>[
        const ProvenanceNotice(
          title: 'DEMO — not live bed telemetry',
          message: 'NEMRAS has no bed-management system, no '
              'admission-discharge-transfer feed and no room sensors. Every '
              'figure on this page is generated by a local demo provider so '
              'the occupancy layout has something to render. Room numbers are '
              'formatted after the dataset Room_Number column, which no '
              'backend route exposes and which carries no room state. None of '
              'these rooms exists and none of these states was measured.',
        ),
        OpsWrapGrid(
          children: <Widget>[
            OpsKpiCard(
              metric: controller.occupiedRoomsKpi,
              icon: Icons.bed_outlined,
            ),
            OpsKpiCard(
              metric: controller.availableRoomsKpi,
              icon: Icons.meeting_room_outlined,
            ),
            OpsKpiCard(
              metric: OpsMetric.demo(
                label: 'Rooms in Turnover',
                value: snapshot.turnoverRooms,
                basis: 'Demo occupancy provider',
                caption: 'Simulated. NEMRAS has no bed telemetry.',
              ),
              icon: Icons.cleaning_services_outlined,
            ),
            OpsKpiCard(
              metric: OpsMetric.demo(
                label: 'Rooms Closed',
                value: snapshot.closedRooms,
                basis: 'Demo occupancy provider',
                caption: 'Simulated. NEMRAS has no bed telemetry.',
              ),
              icon: Icons.do_not_disturb_on_outlined,
            ),
            OpsKpiCard(
              metric: OpsMetric.unavailable(
                label: 'Mean Length of Stay',
                basis: 'No admission/discharge timestamps in NEMRAS',
                caption: 'Requires an admission-discharge-transfer source.',
              ),
              icon: Icons.schedule_outlined,
            ),
          ],
        ),
        const SizedBox(height: NemrasSpacing.section),
        OpsSectionHeader(
          title: 'Occupancy by ward',
          subtitle: '${snapshot.occupiedRooms} of ${snapshot.totalRooms} '
              'simulated rooms occupied overall.',
          trailing: const DemoChip(label: 'DEMO / DATASET-DERIVED'),
        ),
        const SizedBox(height: NemrasSpacing.xxl),
        OpsWrapGrid(
          minTileWidth: 320,
          children: <Widget>[
            for (final ward in snapshot.wards) _WardCard(ward: ward),
          ],
        ),
        const SizedBox(height: NemrasSpacing.section),
        const OpsSectionHeader(
          title: 'Room detail',
          subtitle: 'Every room the demo provider generated, with its '
              'simulated state.',
          trailing: ProvenanceBadge(MetricProvenance.demo),
        ),
        const SizedBox(height: NemrasSpacing.xxl),
        OpsCard(
          child: OpsTable(
            columns: const <OpsColumn>[
              OpsColumn(label: 'Ward', flex: 3),
              OpsColumn(label: 'Rooms', flex: 1, alignEnd: true),
              OpsColumn(label: 'Occupied', flex: 1, alignEnd: true),
              OpsColumn(label: 'Available', flex: 1, alignEnd: true),
              OpsColumn(label: 'Turnover', flex: 1, alignEnd: true),
              OpsColumn(label: 'Closed', flex: 1, alignEnd: true),
              OpsColumn(label: 'Occupancy', flex: 2, alignEnd: true),
            ],
            rows: <List<Widget>>[
              for (final ward in snapshot.wards)
                <Widget>[
                  OpsTextCell(ward.ward),
                  OpsMonoCell('${ward.total}'),
                  OpsMonoCell('${ward.occupied}', emphasise: true),
                  OpsMonoCell('${ward.available}'),
                  OpsMonoCell('${ward.turnover}'),
                  OpsMonoCell('${ward.closed}'),
                  OpsStatusPill(
                    label: ward.occupancyPercentLabel,
                    status: _pressureColour(
                      ward.occupancyFraction,
                      semantics,
                    ),
                  ),
                ],
            ],
          ),
        ),
      ],
    );
  }

  static NemrasStatusColor _pressureColour(
    double fraction,
    NemrasSemantics semantics,
  ) {
    if (fraction >= 0.9) return semantics.critical;
    if (fraction >= 0.75) return semantics.elevated;
    return semantics.stable;
  }
}

/// One ward, with its occupancy bar and a room-state grid.
class _WardCard extends StatelessWidget {
  const _WardCard({required this.ward});

  final WardOccupancy ward;

  @override
  Widget build(BuildContext context) {
    final semantics = NemrasSemantics.of(context);
    final pressure = BedOccupancyScreen._pressureColour(
      ward.occupancyFraction,
      semantics,
    );

    return OpsCard(
      accent: pressure.solid,
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: <Widget>[
          Row(
            children: <Widget>[
              Expanded(
                child: Text(
                  ward.ward,
                  style: NemrasTextStyles.sectionTitle.copyWith(
                    color: semantics.textPrimary,
                  ),
                  overflow: TextOverflow.ellipsis,
                ),
              ),
              OpsStatusPill(
                label: ward.occupancyPercentLabel,
                status: pressure,
              ),
            ],
          ),
          const SizedBox(height: NemrasSpacing.m),
          OpsProgressBar(
            fraction: ward.occupancyFraction,
            color: pressure.solid,
            height: 10,
          ),
          const SizedBox(height: NemrasSpacing.m),
          Text(
            '${ward.occupied} occupied, ${ward.available} available, '
            '${ward.turnover} in turnover, ${ward.closed} closed.',
            style: NemrasTextStyles.bodySmall.copyWith(
              color: semantics.textSecondary,
            ),
          ),
          const SizedBox(height: NemrasSpacing.xl),
          const OpsLabel('Simulated rooms'),
          const SizedBox(height: NemrasSpacing.s),
          Wrap(
            spacing: NemrasSpacing.xxs,
            runSpacing: NemrasSpacing.xxs,
            children: <Widget>[
              for (final room in ward.rooms) _RoomChip(room: room),
            ],
          ),
        ],
      ),
    );
  }
}

/// A single room tile.
class _RoomChip extends StatelessWidget {
  const _RoomChip({required this.room});

  final RoomOccupancy room;

  @override
  Widget build(BuildContext context) {
    final semantics = NemrasSemantics.of(context);
    final NemrasStatusColor status;
    switch (room.state) {
      case RoomState.occupied:
        status = semantics.critical;
      case RoomState.available:
        status = semantics.stable;
      case RoomState.cleaning:
        status = semantics.elevated;
      case RoomState.closed:
        status = semantics.informational;
    }

    return Tooltip(
      message: 'Room ${room.roomNumber}, ${room.ward}\n'
          '${room.state.label} (simulated)',
      child: Container(
        width: 38,
        padding: const EdgeInsets.symmetric(vertical: NemrasSpacing.xxs),
        decoration: BoxDecoration(
          color: status.soft,
          borderRadius: NemrasRadii.tagBorder,
        ),
        child: Text(
          room.roomNumber,
          textAlign: TextAlign.center,
          style: NemrasTextStyles.dataCaption.copyWith(color: status.onSoft),
        ),
      ),
    );
  }
}
